const dictionary=new Map(phrases.map(row=>[row[0],row]));
export function translate(source,language='zh-CN'){
  const index=Math.max(0,languages.indexOf(language)),key=source.trim();
  if(index===0)return source;
  let result=dictionary.get(key)?.[index],m;
  if(result===undefined){
    if((m=key.match(/^共同作品 · 已留下 (\d+) 笔$/)))result=index===1?`共同作品 · 已留下 ${m[1]} 筆`:`Shared artwork · ${m[1]} strokes`;
    else if((m=key.match(/^装置已连接 · (\d+) 笔等候中$/)))result=index===1?`裝置已連線 · ${m[1]} 筆等候中`:`Display connected · ${m[1]} strokes queued`;
    else if((m=key.match(/^这一笔已收下，前面还有 (\d+) 笔。请留意眼前的宣纸。$/)))result=index===1?`這一筆已收下，前面還有 ${m[1]} 筆。請留意眼前的宣紙。`:`Your stroke is queued behind ${m[1]} others. Watch the paper in front of you.`;
    else if((m=key.match(/^已生成 (\d+) 笔共同作品。若未自动下载，可打开图片保存。$/)))result=index===1?`已產生 ${m[1]} 筆共同作品。若未自動下載，可開啟圖片儲存。`:`Artwork with ${m[1]} strokes is ready. If the download did not start, open the image to save it.`;
    else if(key.includes(' / '))result=key.split(' / ').map(part=>translate(part,language)).join(' / ');
    else if(key.includes(' · '))result=key.split(' · ').map(part=>translate(part,language)).join(' · ');
    else return source;
  }
  return source.slice(0,source.length-source.trimStart().length)+result+source.slice(source.trimEnd().length);
}
export function preferredLanguage(value=''){
  if(/^zh/i.test(value))return /(?:TW|HK|MO|Hant)/i.test(value)?'zh-TW':'zh-CN';
  return 'en';
}

// Translate text leaves rather than replacing controls: selections and listeners survive.
export function initLanguage(){
  let language;try{language=localStorage.getItem('wufang-language');}catch{}
  if(!languages.includes(language))language=preferredLanguage(navigator.language);
  const control=document.createElement('label');control.className='language-control';control.dataset.noTranslate='';
  control.innerHTML='<span>语言 / Language</span><select aria-label="语言 / Language"><option value="zh-CN">简体中文</option><option value="zh-TW">繁體中文</option><option value="en">English</option></select>';
  const host=document.querySelector('.masthead')||document.querySelector('.guest')||document.getElementById('screen-settings');
  host.prepend(control);const select=control.querySelector('select');select.value=language;
  const originals=new WeakMap(),attributes=new WeakMap();
  function render(){
    document.documentElement.lang=language;
    const walker=document.createTreeWalker(document.documentElement,NodeFilter.SHOW_TEXT);let node;
    while((node=walker.nextNode())){
      if(!node.textContent.trim()||node.parentElement?.closest('script,style,[data-no-translate]'))continue;
      const previous=originals.get(node),source=previous&&node.textContent===previous.output?previous.source:node.textContent;
      const output=translate(source,language);originals.set(node,{source,output});if(node.textContent!==output)node.textContent=output;
    }
    for(const element of document.querySelectorAll('[aria-label],[alt],[title]')){
      if(element.closest('[data-no-translate]'))continue;
      let saved=attributes.get(element)||{};
      for(const name of ['aria-label','alt','title'])if(element.hasAttribute(name)){
        const current=element.getAttribute(name),old=saved[name],source=old&&current===old.output?old.source:current,output=translate(source,language);
        saved[name]={source,output};if(current!==output)element.setAttribute(name,output);
      }
      attributes.set(element,saved);
    }
  }
  const observer=new MutationObserver(()=>{observer.disconnect();render();observe();});
  function observe(){observer.observe(document.documentElement,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['aria-label','alt','title']});}
  select.onchange=()=>{language=select.value;try{localStorage.setItem('wufang-language',language);}catch{}observer.disconnect();render();observe();};
  render();observe();
  return source=>translate(source,language);
}
